# -*- coding: utf-8 -*-
"""בדיקות ל-common/rtl.py: מסמך עברי שנבנה דרך המודול עובר את הבדיקה; מסמך שנבנה בלי האכיפה נכשל בה."""
import datetime as dt
import os
import zipfile

import pb_helpers  # noqa: F401  מוסיף את שורש החבילה ל-sys.path
from docx import Document

from common import rtl


def _build(path):
    doc = Document()
    rtl.add_paragraph(doc, 'כותרת המסמך', bold=True, size=14)
    rtl.add_paragraph(doc, ltr_parts=[('הסעיף חל לפי ', False), ('Section 5(a)', True), (' של ההסכם.', False)])
    rtl.add_numbered_list(doc, ['פריט ראשון', 'פריט שני'])
    t = doc.add_table(rows=2, cols=3)
    for i, h in enumerate(('נושא', 'ירוק', 'צהוב')):
        t.rows[0].cells[i].text = h
        t.rows[1].cells[i].text = 'תא %d' % i
    rtl.set_table_rtl(t)
    doc.sections[0].header.paragraphs[0].text = 'פלייבוק מוצע, מבוסס מחקר שוק, טעון אישור'
    rtl.enforce_document(doc, author='EXAMPLECO', title='בדיקה')
    doc.save(path)
    return path


def test_enforced_document_passes_audit(tmp_path):
    p = _build(str(tmp_path / 'ok.docx'))
    assert rtl.audit_docx(p, run_date=dt.date.today()) == []


def test_numbering_is_number_then_dot(tmp_path):
    p = _build(str(tmp_path / 'num.docx'))
    with zipfile.ZipFile(p) as z:
        xml = z.read('word/numbering.xml').decode('utf-8')
    assert 'w:val="%1."' in xml
    assert 'w:val=".%1"' not in xml


def test_table_columns_reversed_and_cells_rtl(tmp_path):
    p = _build(str(tmp_path / 'tbl.docx'))
    with zipfile.ZipFile(p) as z:
        xml = z.read('word/document.xml').decode('utf-8')
    assert '<w:bidiVisual/>' in xml
    assert '<w:rtlGutter/>' in xml


def test_latin_run_stays_ltr_inside_hebrew_paragraph(tmp_path):
    p = _build(str(tmp_path / 'mixed.docx'))
    with zipfile.ZipFile(p) as z:
        xml = z.read('word/document.xml').decode('utf-8')
    i = xml.index('Section 5(a)')
    run_start = xml.rfind('<w:r>', 0, i)
    assert '<w:rtl w:val="0"/>' in xml[run_start:i]


def test_plain_python_docx_fails_audit(tmp_path):
    doc = Document()
    doc.add_paragraph('מסמך בלי אכיפה')
    doc.add_table(rows=1, cols=2).rows[0].cells[0].text = 'תא'
    p = str(tmp_path / 'bad.docx')
    doc.save(p)
    problems = rtl.audit_docx(p, run_date=dt.date.today())
    joined = '\n'.join(problems)
    assert 'פסקה בלי bidi' in joined
    assert 'ריצה בלי rtl' in joined
    assert 'bidiVisual' in joined
    assert 'rtlGutter' in joined
    assert 'python-docx' in joined  # docProps/core.xml של התבנית: "generated by python-docx" ותאריך 2013


def test_metadata_cleaned(tmp_path):
    p = _build(str(tmp_path / 'meta.docx'))
    with zipfile.ZipFile(p) as z:
        core = z.read('docProps/core.xml').decode('utf-8')
    assert 'python-docx' not in core
    assert '2013-12-23' not in core
    assert os.path.getsize(p) > 0
