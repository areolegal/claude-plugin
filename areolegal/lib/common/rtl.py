# -*- coding: utf-8 -*-
"""common/rtl.py: אכיפה ובדיקה של RTL מלא בקובצי Word בעברית (python-docx + lxml).

מימוש ייחוס לכל הרכיבים שמפיקים Word בעברית: בונה הפלייבוק (הפלייבוק, גיליון העמדות),
הנושא ונותן (קובץ העבודה ועותק המשלוח) ומעריך הסיכונים.
נגזר מ-rtl-docx-enforcer/rtl_helpers.py (סדר הסכמה, bidi, rtl, טבלאות) ומ-c2m/rtl_check.py (הבדיקה).

הכללים (נבדקים ב-audit_docx):
1. `w:bidi` בכל פסקה שיש בה טקסט: בגוף, בטבלאות, בכותרות עליונות ותחתונות ובהערות.
2. `w:rtl` בכל ריצה שיש בה אות עברית. ריצה בלי אות עברית (נוסח לטיני, קוד, כתובת, ספרות) תקינה בלי `w:rtl`
   או עם `w:rtl w:val="0"` (הערות הנושא ונותן 4.9, שינוי 87: המנוע של עקוב אחר שינויים כותב קטע לטיני בלי rtl).
   ריצה עברית שסומנה LTR היא כשל.
3. יישור: ב-bidi ברירת המחדל (start) היא ימין. jc="left"/"right" מוסרים, כי ב-bidi הם מתהפכים בגרסאות שונות של Word.
4. מספור: lvlText הוא "%1." (מספר ואחריו נקודה). ".%1" הוא כשל.
5. טבלאות: `w:bidiVisual` בכל טבלה, כך שהעמודה הלוגית הראשונה מוצגת מימין; bidi בכל פסקה בכל תא.
6. מקטע: `w:bidi` ו-`w:rtlGutter` בכל `w:sectPr`.
7. גופן עברי (David) ל-cs ולריצות עבריות.
8. מאפייני הקובץ: אין "python-docx" ב-core.xml, ותאריכי היצירה והשינוי אינם מוקדמים מיום ההפקה
   (ממצא 14 של המהנדס בסבב 2: ה-Word של הבונה נשא תאריך 2013 ו"generated by python-docx").
"""
import datetime as _dt
import re
import zipfile

from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Pt
from lxml import etree

W_NS = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'
HEBREW_FONT = 'David'

_ORDER_PPR = ("pStyle", "keepNext", "keepLines", "pageBreakBefore", "framePr", "widowControl", "numPr",
              "suppressLineNumbers", "pBdr", "shd", "tabs", "suppressAutoHyphens", "kinsoku", "wordWrap",
              "overflowPunct", "topLinePunct", "autoSpaceDE", "autoSpaceDN", "bidi", "adjustRightInd",
              "snapToGrid", "spacing", "ind", "contextualSpacing", "mirrorIndents", "suppressOverlap", "jc",
              "textDirection", "textAlignment", "textboxTightWrap", "outlineLvl", "divId", "cnfStyle", "rPr",
              "sectPr", "pPrChange")
_ORDER_RPR = ("rStyle", "rFonts", "b", "bCs", "i", "iCs", "caps", "smallCaps", "strike", "dstrike", "outline",
              "shadow", "emboss", "imprint", "noProof", "snapToGrid", "vanish", "webHidden", "color", "spacing",
              "w", "kern", "position", "sz", "szCs", "highlight", "u", "effect", "bdr", "shd", "fitText",
              "vertAlign", "rtl", "cs", "em", "lang", "eastAsianLayout", "specVanish", "oMath", "rPrChange")
_ORDER_TBLPR = ("tblStyle", "tblpPr", "tblOverlap", "bidiVisual", "tblStyleRowBandSize", "tblStyleColBandSize",
                "tblW", "jc", "tblCellSpacing", "tblInd", "tblBorders", "shd", "tblLayout", "tblCellMar",
                "tblLook", "tblCaption", "tblDescription", "tblPrChange")
_ORDER_SECTPR = ("footnotePr", "endnotePr", "type", "pgSz", "pgMar", "paperSrc", "pgBorders", "lnNumType",
                 "pgNumType", "cols", "formProt", "vAlign", "noEndnote", "titlePg", "textDirection", "bidi",
                 "rtlGutter", "docGrid", "printerSettings", "sectPrChange")
_ORDER_LVL = ("start", "numFmt", "lvlRestart", "pStyle", "isLgl", "suff", "lvlText", "lvlPicBulletId",
              "legacy", "lvlJc", "pPr", "rPr")

RTL_STYLES = ("Normal", "Heading 1", "Heading 2", "Heading 3", "Title", "Subtitle", "List Paragraph",
              "List Number", "List Bullet", "Table Grid")
_HEB = re.compile('[֐-׿]')


# ------------------------------------------------------------------ סדר סכמה
def _ensure(parent, tag, order):
    """מחזיר את התג אם קיים; אחרת מכניס אותו במקומו לפי סדר הסכמה (ולא בסוף המכל)."""
    found = parent.find(qn(tag))
    if found is not None:
        return found
    name = tag.split(':', 1)[1]
    rank = order.index(name)
    el = OxmlElement(tag)
    for i, child in enumerate(parent):
        cname = child.tag.split('}')[-1]
        if cname in order and order.index(cname) > rank:
            parent.insert(i, el)
            return el
    parent.append(el)
    return el


def _child(parent, tag, first=True):
    el = parent.find(qn(tag))
    if el is None:
        el = OxmlElement(tag)
        if first:
            parent.insert(0, el)
        else:
            parent.append(el)
    return el


# ------------------------------------------------------------------ פסקה וריצה
def _ppr_rtl(p_el):
    pPr = _child(p_el, 'w:pPr')
    _ensure(pPr, 'w:bidi', _ORDER_PPR)
    for jc in pPr.findall(qn('w:jc')):
        if jc.get(qn('w:val')) in ('left', 'right'):
            pPr.remove(jc)
    return pPr


def _is_explicit_ltr(r_el):
    rPr = r_el.find(qn('w:rPr'))
    if rPr is None:
        return False
    el = rPr.find(qn('w:rtl'))
    return el is not None and el.get(qn('w:val')) in ('0', 'false')


def _rpr_rtl(r_el, font=HEBREW_FONT):
    if _is_explicit_ltr(r_el):
        return
    rPr = _child(r_el, 'w:rPr')
    fonts = _ensure(rPr, 'w:rFonts', _ORDER_RPR)
    fonts.set(qn('w:cs'), font)
    _ensure(rPr, 'w:rtl', _ORDER_RPR)


def set_run_rtl(run, font=HEBREW_FONT, size=None):
    if size:
        run.font.size = Pt(size)
        rPr = _child(run._r, 'w:rPr')
        _ensure(rPr, 'w:szCs', _ORDER_RPR).set(qn('w:val'), str(int(size * 2)))
    fonts = _ensure(_child(run._r, 'w:rPr'), 'w:rFonts', _ORDER_RPR)
    for att in ('w:ascii', 'w:hAnsi'):
        fonts.set(qn(att), font)
    _rpr_rtl(run._r, font)
    return run


def set_run_ltr(run):
    """ריצה לטינית (קוד, כתובת, נוסח באנגלית) בתוך פסקה עברית: LTR מפורש."""
    rPr = _child(run._r, 'w:rPr')
    for el in rPr.findall(qn('w:rtl')):
        rPr.remove(el)
    _ensure(rPr, 'w:rtl', _ORDER_RPR).set(qn('w:val'), '0')
    return run


def set_paragraph_rtl(paragraph, font=HEBREW_FONT):
    _ppr_rtl(paragraph._p)
    for r in paragraph._p.iter(qn('w:r')):
        _rpr_rtl(r, font)
    return paragraph


def add_paragraph(container, text='', bold=False, size=11, ltr_parts=None):
    """פסקה עברית. ltr_parts: [(text, True|False)] כשיש בפסקה קטעים לטיניים שיישארו LTR."""
    p = container.add_paragraph()
    parts = ltr_parts or [(text, False)]
    for chunk, is_ltr in parts:
        if not chunk:
            continue
        r = p.add_run(chunk)
        r.bold = bold
        if is_ltr:
            r.font.size = Pt(size)
            set_run_ltr(r)
        else:
            set_run_rtl(r, size=size)
    set_paragraph_rtl(p)
    return p


# ------------------------------------------------------------------ טבלה ומקטע
def set_table_rtl(table):
    """bidiVisual: העמודה הלוגית הראשונה מוצגת מימין (היפוך הסדר החזותי), ו-RTL בכל תא."""
    tbl = table._tbl
    tblPr = _child(tbl, 'w:tblPr')
    _ensure(tblPr, 'w:bidiVisual', _ORDER_TBLPR)
    for p in tbl.iter(qn('w:p')):
        _ppr_rtl(p)
        for r in p.iter(qn('w:r')):
            _rpr_rtl(r)
    return table


def set_section_rtl(section):
    sp = section._sectPr
    _ensure(sp, 'w:bidi', _ORDER_SECTPR)
    _ensure(sp, 'w:rtlGutter', _ORDER_SECTPR)
    return section


def set_styles_rtl(doc):
    for name in RTL_STYLES:
        try:
            st = doc.styles[name]
        except KeyError:
            continue
        pPr = st.element.find(qn('w:pPr'))
        if pPr is None:
            pPr = OxmlElement('w:pPr')
            st.element.append(pPr)
        _ensure(pPr, 'w:bidi', _ORDER_PPR)
        rPr = st.element.find(qn('w:rPr'))
        if rPr is None:
            rPr = OxmlElement('w:rPr')
            st.element.append(rPr)
        _ensure(rPr, 'w:rFonts', _ORDER_RPR).set(qn('w:cs'), HEBREW_FONT)
        _ensure(rPr, 'w:rtl', _ORDER_RPR)


# ------------------------------------------------------------------ מספור "1."
def add_numbered_list(doc, items, size=11):
    """רשימה ממוספרת אמיתית (numbering.xml) בפורמט "1." ו-RTL. מחזיר את הפסקאות."""
    numbering = doc.part.numbering_part.element
    abs_ids = [int(a.get(qn('w:abstractNumId'))) for a in numbering.findall(qn('w:abstractNum'))]
    num_ids = [int(n.get(qn('w:numId'))) for n in numbering.findall(qn('w:num'))]
    abs_id = max(abs_ids + [0]) + 1
    num_id = max(num_ids + [0]) + 1
    absn = OxmlElement('w:abstractNum')
    absn.set(qn('w:abstractNumId'), str(abs_id))
    lvl = OxmlElement('w:lvl')
    lvl.set(qn('w:ilvl'), '0')
    for tag, val in (('w:start', '1'), ('w:numFmt', 'decimal'), ('w:lvlText', '%1.'), ('w:lvlJc', 'left')):
        el = _ensure(lvl, tag, _ORDER_LVL)
        el.set(qn('w:val'), val)
    lpPr = _ensure(lvl, 'w:pPr', _ORDER_LVL)
    _ensure(lpPr, 'w:bidi', _ORDER_PPR)
    ind = _ensure(lpPr, 'w:ind', _ORDER_PPR)
    ind.set(qn('w:right'), '360')
    ind.set(qn('w:hanging'), '360')
    absn.append(lvl)
    first_num = numbering.find(qn('w:num'))
    if first_num is not None:
        first_num.addprevious(absn)
    else:
        numbering.append(absn)
    num = OxmlElement('w:num')
    num.set(qn('w:numId'), str(num_id))
    an = OxmlElement('w:abstractNumId')
    an.set(qn('w:val'), str(abs_id))
    num.append(an)
    numbering.append(num)
    out = []
    for item in items:
        p = add_paragraph(doc, item, size=size)
        pPr = _child(p._p, 'w:pPr')
        numPr = _ensure(pPr, 'w:numPr', _ORDER_PPR)
        _child(numPr, 'w:ilvl').set(qn('w:val'), '0')
        numId = numPr.find(qn('w:numId'))
        if numId is None:
            numId = OxmlElement('w:numId')
            numPr.append(numId)
        numId.set(qn('w:val'), str(num_id))
        out.append(p)
    return out


# ------------------------------------------------------------------ מאפייני הקובץ
def utc_naive(when=None):
    """datetime נאיבי ב-UTC, לכתיבה ב-core.xml עם "Z"."""
    if when is None:
        when = _dt.datetime.now(_dt.timezone.utc)
    elif when.tzinfo is None:
        when = when.astimezone()  # נאיבי = שעון מקומי
    return when.astimezone(_dt.timezone.utc).replace(tzinfo=None, microsecond=0)


def clean_metadata(doc, author='', title=None, when=None):
    """מנקה את סימני python-docx ומציב תאריך הפקה אמיתי. לקרוא לפני כל doc.save.

    python-docx כותב את התאריך כפי שהוא ומוסיף "Z" (UTC). לכן התאריך מומר כאן ל-UTC אמיתי: בלי when, השעה עכשיו
    ב-UTC; when עם אזור זמן מומר ל-UTC; when נאיבי נחשב שעון מקומי ומומר ל-UTC (ממצא 14 של המהנדס: שעה מקומית
    עם "Z" הזיזה את חותמת הזמן בשעתיים או שלוש)."""
    when = utc_naive(when)
    cp = doc.core_properties
    cp.author = author or ''
    cp.last_modified_by = author or ''
    cp.comments = ''
    cp.keywords = ''
    cp.subject = ''
    if title is not None:
        cp.title = title
    cp.revision = 1
    cp.created = when
    cp.modified = when
    cp.last_printed = when
    return doc


def enforce_document(doc, author='', title=None):
    """רשת ביטחון למסמך שלם: מקטעים, סגנונות, כל הפסקאות והריצות (גוף, טבלאות, כותרות), ומאפיינים.

    נוגע רק במאפייני פסקה, ריצה, טבלה ומקטע. אינו נוגע ב-w:ins, w:del ובעוגני הערות, ולכן בטוח גם
    למסמך עם עקוב אחר שינויים."""
    for section in doc.sections:
        set_section_rtl(section)
        for hf in (section.header, section.footer):
            for p in hf._element.iter(qn('w:p')):
                _ppr_rtl(p)
                for r in p.iter(qn('w:r')):
                    _rpr_rtl(r)
    set_styles_rtl(doc)
    body = doc.element.body
    for tbl in body.iter(qn('w:tbl')):
        _ensure(_child(tbl, 'w:tblPr'), 'w:bidiVisual', _ORDER_TBLPR)
    for p in body.iter(qn('w:p')):
        _ppr_rtl(p)
        for r in p.iter(qn('w:r')):
            _rpr_rtl(r)
    clean_metadata(doc, author=author, title=title)
    return doc


# ------------------------------------------------------------------ בדיקה
def _q(tag):
    return '{%s}%s' % (W_NS, tag)


def _text(el):
    return ''.join(t.text or '' for t in el.iter(_q('t')))


def audit_docx(path, run_date=None, require_hebrew=True):
    """בודק קובץ docx שמור. מחזיר רשימת בעיות (ריקה = עבר). לא מתקן.

    run_date: תאריך ההפקה (date); מאפייני הקובץ אינם יכולים להיות מוקדמים ממנו."""
    problems = []
    with zipfile.ZipFile(path) as z:
        names = z.namelist()
        parts = ['word/document.xml'] + sorted(n for n in names if re.match(
            r'word/(header|footer)\d*\.xml$|word/comments\.xml$', n))
        has_hebrew = False
        for part in parts:
            x = etree.fromstring(z.read(part))
            for p in x.iter(_q('p')):
                t = _text(p)
                if not t.strip():
                    continue
                has_hebrew = has_hebrew or bool(_HEB.search(t))
                ppr = p.find(_q('pPr'))
                if ppr is None or ppr.find(_q('bidi')) is None:
                    problems.append('%s: פסקה בלי bidi: %s' % (part, t[:40]))
                elif any(j.get(_q('val')) in ('left', 'right') for j in ppr.findall(_q('jc'))):
                    problems.append('%s: יישור מפורש left/right בפסקה RTL: %s' % (part, t[:40]))
            for r in x.iter(_q('r')):
                t = _text(r)
                if not t.strip():
                    continue
                rpr = r.find(_q('rPr'))
                rtl = rpr.find(_q('rtl')) if rpr is not None else None
                if rtl is None and not _HEB.search(t):
                    continue  # ריצה לטינית או ניטרלית: LTR תקין גם בלי w:rtl
                if rtl is None:
                    problems.append('%s: ריצה בלי rtl: %s' % (part, t[:40]))
                elif rtl.get(_q('val')) in ('0', 'false') and _HEB.search(t):
                    problems.append('%s: ריצה עברית שסומנה LTR: %s' % (part, t[:40]))
            for tb in x.iter(_q('tbl')):
                tp = tb.find(_q('tblPr'))
                if tp is None or tp.find(_q('bidiVisual')) is None:
                    problems.append('%s: טבלה בלי bidiVisual (סדר העמודות לא הפוך)' % part)
        doc = etree.fromstring(z.read('word/document.xml'))
        sects = list(doc.iter(_q('sectPr')))
        if not sects:
            problems.append('אין sectPr במסמך')
        for sp in sects:
            if sp.find(_q('bidi')) is None:
                problems.append('מקטע בלי bidi')
            if sp.find(_q('rtlGutter')) is None:
                problems.append('מקטע בלי rtlGutter')
        if 'word/numbering.xml' in names:
            nx = etree.fromstring(z.read('word/numbering.xml'))
            for lvl in nx.iter(_q('lvl')):
                fmt = lvl.find(_q('numFmt'))
                lt = lvl.find(_q('lvlText'))
                v = lt.get(_q('val')) if lt is not None else ''
                if fmt is not None and fmt.get(_q('val')) == 'bullet':
                    continue
                if v and re.match(r'^\.\s*%\d', v):
                    problems.append('מספור עם נקודה לפני המספר: %s' % v)
        if 'docProps/core.xml' in names:
            core = z.read('docProps/core.xml').decode('utf-8', 'replace')
            if 'python-docx' in core:
                problems.append('מאפייני הקובץ: "python-docx" ב-core.xml')
            if run_date:
                for tag in ('created', 'modified'):
                    m = re.search(r'<dcterms:%s[^>]*>(\d{4}-\d{2}-\d{2})' % tag, core)
                    if m and m.group(1) < run_date.isoformat():
                        problems.append('מאפייני הקובץ: %s=%s מוקדם מיום ההפקה' % (tag, m.group(1)))
        if require_hebrew and not has_hebrew:
            problems.append('אין טקסט עברי במסמך: הבדיקה חלה על מסמכים בעברית')
    return problems
